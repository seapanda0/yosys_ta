#!/usr/bin/env python3
# Written by Claude, an AI model made by Anthropic (see docs/timing_aware_synthesis.md).
# Generates timing.lib, a tiny NLDM library for the timing tests. The delay tables are linear:
#   delay      = t0 + R * load + 0.1 * input_slew
#   transition = 0.01 + 2 * R * load + 0.05 * input_slew
# (ns, pF), so that expected path delays can be computed by hand.

SLEWS = [0.01, 0.1, 0.5]
LOADS = [0.001, 0.01, 0.1]

def table(kind, name, t0, r):
    rows = []
    for s in SLEWS:
        if kind == "delay":
            rows.append(", ".join("%.5f" % (t0 + r * c + 0.1 * s) for c in LOADS))
        else:
            rows.append(", ".join("%.5f" % (0.01 + 2 * r * c + 0.05 * s) for c in LOADS))
    return '        %s (del) { values(%s); }\n' % (name, ", ".join('"%s"' % r for r in rows))

def arc(related, sense, t0, r, ttype=None):
    s = '      timing () {\n        related_pin : "%s";\n        timing_sense : %s;\n' % (related, sense)
    if ttype:
        s += '        timing_type : %s;\n' % ttype
    s += table("delay", "cell_rise", t0, r) + table("delay", "cell_fall", t0, r)
    s += table("trans", "rise_transition", t0, r) + table("trans", "fall_transition", t0, r)
    return s + '      }\n'

def comb(name, footprint, area, inputs, func, sense, cin, t0, r):
    s = '  cell (%s) {\n    area : %g;\n    cell_footprint : "%s";\n' % (name, area, footprint)
    for i in inputs:
        s += '    pin (%s) { direction : input; capacitance : %g; }\n' % (i, cin)
    s += '    pin (Y) {\n      direction : output;\n      function : "%s";\n      max_capacitance : %g;\n' % (func, 0.6 / r)
    for i in inputs:
        s += arc(i, sense, t0, r)
    return s + '    }\n  }\n'

def dff(name, area, r):
    s = '  cell (%s) {\n    area : %g;\n    cell_footprint : "DFF";\n' % (name, area)
    s += '    ff (IQ, IQN) { next_state : "D"; clocked_on : "CK"; }\n'
    s += '    pin (CK) { direction : input; clock : true; capacitance : 0.002; }\n'
    s += '    pin (D) {\n      direction : input;\n      capacitance : 0.002;\n'
    s += '      timing () {\n        related_pin : "CK";\n        timing_type : setup_rising;\n'
    for n in ("rise_constraint", "fall_constraint"):
        rows = [", ".join("%.5f" % (0.1 + 0.2 * d) for d in SLEWS) for c in SLEWS]
        s += '        %s (chk) { values(%s); }\n' % (n, ", ".join('"%s"' % r for r in rows))
    s += '      }\n    }\n'
    s += '    pin (Q) {\n      direction : output;\n      function : "IQ";\n      max_capacitance : %g;\n' % (0.6 / r)
    s += arc("CK", "non_unate", 0.2, r, "rising_edge")
    return s + '    }\n  }\n'

out = '''/* generated by gen_lib.py, do not edit */
library (timing) {
  delay_model : table_lookup;
  time_unit : "1ns";
  voltage_unit : "1V";
  current_unit : "1mA";
  pulling_resistance_unit : "1kohm";
  leakage_power_unit : "1nW";
  capacitive_load_unit (1, pf);
  default_max_transition : 1.5;
  lu_table_template (del) {
    variable_1 : input_net_transition;
    variable_2 : total_output_net_capacitance;
    index_1 ("%s");
    index_2 ("%s");
  }
  lu_table_template (chk) {
    variable_1 : related_pin_transition;
    variable_2 : constrained_pin_transition;
    index_1 ("%s");
    index_2 ("%s");
  }
''' % (", ".join(map(str, SLEWS)), ", ".join(map(str, LOADS)), ", ".join(map(str, SLEWS)), ", ".join(map(str, SLEWS)))
for x, a in ((1, 1.0), (2, 1.5), (4, 2.5)):
    out += comb("INV_X%d" % x, "INV", a, ["A"], "!A", "negative_unate", 0.002 * x, 0.02, 5.0 / x)
for x, a in ((1, 1.5), (4, 3.0)):
    out += comb("BUF_X%d" % x, "BUF", a, ["A"], "A", "positive_unate", 0.002, 0.06, 5.0 / x)
for x, a in ((1, 1.5), (2, 2.5), (4, 4.5)):
    out += comb("NAND2_X%d" % x, "NAND2", a, ["A", "B"], "!(A&B)", "negative_unate", 0.002 * x, 0.03, 6.0 / x)
    out += comb("NOR2_X%d" % x, "NOR2", a, ["A", "B"], "!(A|B)", "negative_unate", 0.002 * x, 0.04, 8.0 / x)
for x, a in ((1, 3.0), (2, 5.0)):
    out += comb("XOR2_X%d" % x, "XOR2", a, ["A", "B"], "(A&!B)|(!A&B)", "non_unate", 0.004 * x, 0.08, 7.0 / x)
for x, a in ((1, 5.0), (2, 6.5)):
    out += dff("DFF_X%d" % x, a, 5.0 / x)
out += '}\n'
open("timing.lib", "w").write(out)

# DFF_X2 becomes a negative edge flip-flop that still has the footprint and pins of DFF_X1.
# The space in the file name is intended (paths with spaces have to work).
a = out.index("cell (DFF_X2)")
neg = out[a:].replace('clocked_on : "CK"', 'clocked_on : "!CK"')
neg = neg.replace("rising_edge", "falling_edge").replace("setup_rising", "setup_falling")
open("mixed edge.lib", "w").write(out[:a] + neg)
