#!/usr/bin/env python3
"""Generate a self-checking random-simulation testbench that drives an RTL
reference (module ref_top) and a gate-level netlist (module gate_top) with the
same stimulus and compares every output before each rising clock edge.

usage: gen_tb.py <ref.v> <gate.v> <design> <clock_port> <cycles> <seed> <out_tb.v>

Exit status: 0 on success, 2 if the two port lists differ or the files do not
look like the expected single-module flat netlists.
"""
import re
import sys

DECL = re.compile(
    r'^\s*(input|output|inout)\s+(?:wire\s+|reg\s+)?(?:signed\s+)?'
    r'(?:\[\s*(-?\d+)\s*:\s*(-?\d+)\s*\]\s*)?'
    r'(\\\S+|[A-Za-z_]\w*)\s*;',
    re.M,
)
RESET_RE = re.compile(r'rst|reset|clr|clear')


def die(msg):
    print("gen_tb: " + msg)
    sys.exit(2)


def strip_esc(name):
    return name[1:] if name.startswith('\\') else name


def parse(path, modname):
    txt = open(path).read()
    mods = re.findall(r'^module\s+(\S+?)\s*[(;#]', txt, re.M)
    if mods != [modname]:
        die("%s: expected single module '%s', found %s" % (path, modname, mods))
    if re.search(r'^\s*\\\$', txt, re.M):
        die("%s: unmapped yosys internal cell instantiated" % path)
    if 'sky130_fd_sc_hd__' in txt:
        die("%s: still contains sky130 cell instances (not flattened)" % path)
    # Only module-level declarations count; function/task bodies have their own.
    body = re.sub(r'\bfunction\b.*?\bendfunction\b', '', txt, flags=re.S)
    body = re.sub(r'\btask\b.*?\bendtask\b', '', body, flags=re.S)
    ports = []
    for m in DECL.finditer(body):
        d, msb, lsb, name = m.groups()
        w = 1 if msb is None else abs(int(msb) - int(lsb)) + 1
        ports.append((d, w, name))
    return ports


def inactive_level(lname):
    if lname.endswith(('n', '_n', '_b', '_ni', 'n_i')) or \
            any(s in lname for s in ('resetn', 'rstn', 'rst_n')):
        return 1
    return 0


def rand_expr(w):
    n = (w + 31) // 32
    if n == 1:
        return "$random(seed)"
    return "{" + ", ".join("$random(seed)" for _ in range(n)) + "}"


def main():
    if len(sys.argv) != 8:
        die("usage: gen_tb.py ref.v gate.v design clock cycles seed out.v")
    ref_path, gate_path, design, clock, cycles, seed, out = sys.argv[1:8]
    cycles = int(cycles)
    seed = int(seed)

    rports = parse(ref_path, 'ref_top')
    gports = parse(gate_path, 'gate_top')
    rmap = {strip_esc(n): (d, w) for d, w, n in rports}
    gmap = {strip_esc(n): (d, w) for d, w, n in gports}
    if rmap != gmap:
        only_r = sorted(set(rmap) - set(gmap))
        only_g = sorted(set(gmap) - set(rmap))
        diff = [n for n in rmap if n in gmap and rmap[n] != gmap[n]]
        die("port mismatch ref vs gate: only_ref=%s only_gate=%s differing=%s"
            % (only_r, only_g, diff))
    if any(d == 'inout' for d, _, _ in rports):
        die("inout ports are not supported")

    # Port list in declaration order, names as written by yosys.
    ins, outs = [], []
    for d, w, n in rports:
        (ins if d == 'input' else outs).append((strip_esc(n), n, w))

    clk_inputs = [x for x in ins if x[0] == clock or 'clk' in x[0].lower()]
    if clock not in [x[0] for x in ins]:
        die("clock port '%s' is not an input of the top module" % clock)
    clk_set = set(x[0] for x in clk_inputs)
    data_ins = [x for x in ins if x[0] not in clk_set]
    reset_like = [x for x in data_ins if RESET_RE.search(x[0].lower())]
    other_ins = [x for x in data_ins if x not in reset_like]
    total_out_bits = sum(w for _, _, w in outs)

    L = []
    A = L.append
    A("// Generated by verify/gen_tb.py -- do not edit.")
    A("`timescale 1ns/1ps")
    A("module tb;")
    A("  reg clk = 1'b0;")
    A("  integer seed = %d;" % seed)
    A("  integer mism = 0;")
    A("  integer first_mism = -1;")
    A("  integer pre = 0;            // mismatches before reset has taken effect")
    A("  integer rst_first = -1;     // first cycle in which a reset-like input is active")
    A("  reg [8*4-1:0] status;")
    A("")
    # input registers (clock-like ones use clk directly)
    for k, (pn, n, w) in enumerate(data_ins):
        A("  reg [%d:0] iv%d;" % (w - 1, k))
    for k, (pn, n, w) in enumerate(outs):
        A("  wire [%d:0] rq%d, gq%d;" % (w - 1, k, k))
        A("  reg  [%d:0] prv%d, tog%d;" % (w - 1, k, k))
    A("")

    def conn_list(prefix):
        conns = []
        for pn, n, w in ins:
            if pn in clk_set:
                conns.append(".%s(clk)" % n)
            else:
                k = [x[0] for x in data_ins].index(pn)
                conns.append(".%s(iv%d)" % (n, k))
        for k, (pn, n, w) in enumerate(outs):
            conns.append(".%s(%s%d)" % (n, prefix, k))
        return ",\n    ".join(conns)

    A("  ref_top u_ref (")
    A("    " + conn_list("rq"))
    A("  );")
    A("  gate_top u_gate (")
    A("    " + conn_list("gq"))
    A("  );")
    A("")

    # ---- stimulus task -------------------------------------------------
    A("  // cycles 0-19: zeros, 20-39: ones, 40-59: zeros (resets asserted in")
    A("  // whichever phase matches their polarity); afterwards random data,")
    A("  // reset-like inputs at their inactive level with 1-cycle pulses (p=1/200).")
    A("  task drive(input integer c);")
    A("    reg pulse;")
    A("    begin")
    A("      if (c >= 60) begin")
    for k, (pn, n, w) in enumerate(other_ins):
        A("        iv%d = %s;" % (data_ins.index((pn, n, w)), rand_expr(w)))
    for pn, n, w in reset_like:
        k = data_ins.index((pn, n, w))
        inact = inactive_level(pn)
        A("        pulse = ($unsigned($random(seed)) % 200) == 0;")
        A("        iv%d = pulse ? {%d{1'b%d}} : {%d{1'b%d}};"
          % (k, w, 1 - inact, w, inact))
    A("      end else begin")
    A("        if (c >= 20 && c < 40) begin")
    for k, (pn, n, w) in enumerate(data_ins):
        A("          iv%d = {%d{1'b1}};" % (k, w))
    A("        end else begin")
    for k, (pn, n, w) in enumerate(data_ins):
        A("          iv%d = {%d{1'b0}};" % (k, w))
    A("        end")
    A("      end")
    if reset_like:
        A("      if (rst_first < 0) begin")
        conds = []
        for pn, n, w in reset_like:
            k = data_ins.index((pn, n, w))
            conds.append("iv%d == {%d{1'b%d}}" % (k, w, 1 - inactive_level(pn)))
        A("        if (%s) rst_first = c;" % " || ".join(conds))
        A("      end")
    A("    end")
    A("  endtask")
    A("")

    # ---- compare task ----------------------------------------------------
    A("  // Mismatches are counted only once reset has taken effect: before the first")
    A("  // clock edge with reset active, the two designs start from different")
    A("  // power-on states when the flow re-encodes an FSM (zero-init is not the reset")
    A("  // state). Such mismatches are printed as PRERESET_MISMATCH and not counted.")
    A("  task check(input integer c);")
    A("    integer counted;")
    A("    begin")
    if reset_like:
        A("      counted = (rst_first >= 0 && c > rst_first);")
    else:
        A("      counted = 1;")
    for k, (pn, n, w) in enumerate(outs):
        A("      if (rq%d !== gq%d) begin" % (k, k))
        A("        if (counted) begin")
        A("          mism = mism + 1;")
        A("          if (first_mism < 0) first_mism = c;")
        A("          $display(\"MISMATCH cycle=%%0d port=%s ref=%%h gate=%%h\", c, rq%d, gq%d);"
          % (pn, k, k))
        A("        end else begin")
        A("          pre = pre + 1;")
        A("          $display(\"PRERESET_MISMATCH cycle=%%0d port=%s ref=%%h gate=%%h\", c, rq%d, gq%d);"
          % (pn, k, k))
        A("        end")
        A("      end")
        A("      if (c > 0) tog%d = tog%d | (rq%d ^ prv%d);" % (k, k, k, k))
        A("      prv%d = rq%d;" % (k, k))
    A("    end")
    A("  endtask")
    A("")

    # ---- summary task ----------------------------------------------------
    A("  task summary(input integer n);")
    A("    integer b, tcount;")
    A("    begin")
    A("      tcount = 0;")
    for k, (pn, n, w) in enumerate(outs):
        A("      for (b = 0; b < %d; b = b + 1) if (tog%d[b] === 1'b1) tcount = tcount + 1;"
          % (w, k))
    A("      status = (mism == 0) ? \"PASS\" : \"FAIL\";")
    A("      $display(\"VERIFY design=%s cycles=%%0d mismatches=%%0d first_mismatch_cycle=%%0d status=%%0s toggled_outputs=%%0d/%d prereset_mismatches=%%0d\", n, mism, first_mism, status, tcount, pre);"
      % (design, total_out_bits))
    A("    end")
    A("  endtask")
    A("")

    # ---- main sequence ----------------------------------------------------
    A("  initial begin : main")
    A("    integer c;")
    A("    drive(0);")
    A("    for (c = 0; c < %d; c = c + 1) begin" % cycles)
    A("      #4;                 // clk low, outputs settled; compare before the edge")
    A("      check(c);")
    A("      if (mism >= 20) begin")
    A("        summary(c + 1);")
    A("        $finish;")
    A("      end")
    A("      #1 clk = 1'b1;      // rising edge: DUT samples the stimulus of cycle c")
    A("      #1 drive(c + 1);    // new stimulus shortly after the edge")
    A("      #4 clk = 1'b0;")
    A("    end")
    A("    summary(%d);" % cycles)
    A("    $finish;")
    A("  end")
    A("endmodule")
    A("")

    with open(out, 'w') as f:
        f.write("\n".join(L))

    print("gen_tb: design=%s clock=%s clock_like=%s" %
          (design, clock, sorted(clk_set)))
    print("gen_tb: data inputs=%d reset_like=%s outputs=%d output_bits=%d"
          % (len(data_ins), [x[0] for x in reset_like], len(outs), total_out_bits))
    print("gen_tb: ref/gate port lists identical (%d ports)" % len(rports))


if __name__ == '__main__':
    main()
